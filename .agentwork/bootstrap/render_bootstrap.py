def validate_codex_agent(agent: dict) -> None:
    name = agent['name']
    filename = agent['file']
    if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
        raise SystemExit(f'invalid Codex agent name: {name}')
    if Path(filename).name != filename or not filename.endswith('.toml'):
        raise SystemExit(f'invalid Codex agent filename: {filename}')


def render_codex_agent(agent: dict) -> str:
    validate_codex_agent(agent)
    instructions = "\n".join(agent['developer_instructions']).rstrip()
    if '"""' in instructions:
        raise SystemExit(f'Codex agent instructions contain unsupported triple quote: {agent["name"]}')
    instructions = instructions.replace('\\', '\\\\')
    return (
        f"{CODEX_AUTO}\n"
        f"model = {toml_string(agent['model'])}\n"
        f"model_reasoning_effort = {toml_string(agent['model_reasoning_effort'])}\n\n"
        f"developer_instructions = \"\"\"\n{instructions}\n\"\"\"\n"
    )


def render_codex_config_block() -> str:
    out = [CODEX_CONFIG_START, CODEX_AUTO]
    for index, agent in enumerate(SPEC['codex_agents']):
        validate_codex_agent(agent)
        if index:
            out.append('')
        out += [
            f"[agents.{agent['name']}]",
            f"description = {toml_string(agent['description'])}",
            f"config_file = {toml_string('agents/' + agent['file'])}",
        ]
    out += [CODEX_CONFIG_END]
    return "\n".join(out) + "\n"


