def is_python_cache_artifact(rel: Path) -> bool:
    return '__pycache__' in rel.parts or rel.suffix in {'.pyc', '.pyo'}


def atomic_write_bytes(
    path: Path,
    content: bytes,
    *,
    mode_source: Path | None = None,
) -> None:
    """Replace a managed file without following a destination hardlink.

    Writing through ``Path.write_bytes`` mutates the destination inode in place.
    A project-owned hardlink could therefore make an installer update a file
    outside the project.  A same-directory temporary file followed by
    ``os.replace`` changes the directory entry instead and keeps that external
    inode untouched.  Existing/source modes are retained where available;
    newly-created files use the normal repository-document mode.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    mode: int | None = None
    if path.exists() and not path.is_symlink() and path.is_file():
        mode = path.stat().st_mode & 0o7777
    elif mode_source is not None and mode_source.is_file() and not mode_source.is_symlink():
        mode = mode_source.stat().st_mode & 0o7777

    temp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            prefix=f'.{path.name}.',
            dir=path.parent,
            delete=False,
        ) as handle:
            temp_name = handle.name
            os.chmod(temp_name, mode if mode is not None else 0o644)
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_name, path)
        temp_name = None
    finally:
        if temp_name is not None:
            try:
                Path(temp_name).unlink()
            except FileNotFoundError:
                pass


def copy_file(src: Path, dst: Path) -> None:
    if src.resolve() == dst.resolve():
        return
    if dst.exists() and dst.is_dir():
        raise SystemExit(f'target path is a directory, expected file: {dst}')
    atomic_write_bytes(dst, src.read_bytes(), mode_source=src)


def prune_empty_parents(path: Path, project_root: Path) -> None:
    current = path
    while current != project_root and current.exists():
        try:
            current.rmdir()
        except OSError:
            break
        current = current.parent


def is_agentwork_owned_retired_adapter(
    rel: Path,
    path: Path,
    previous: dict[str, str],
    previous_receipt_exists: bool,
) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    try:
        content = path.read_bytes()
        text = content.decode('utf-8')
    except (OSError, UnicodeError):
        return False
    if rel in RETIRED_BOOTSTRAP_PATHS:
        prior_digest = previous.get(rel.as_posix())
        if prior_digest is not None:
            return sha256_bytes(content) == prior_digest
        return not previous_receipt_exists and AGENTWORK_BOOTSTRAP_MARKER in text
    signatures = RETIRED_TOOL_SIGNATURES.get(rel, ())
    return bool(signatures) and all(signature in text for signature in signatures)


def classify_retired_adapters(
    target: Path,
    previous: dict[str, str],
    previous_receipt_exists: bool,
) -> tuple[tuple[Path, ...], tuple[Path, ...]]:
    removed = []
    preserved = []
    for rel in RETIRED_ADAPTER_PATHS:
        path = target / rel
        if not path.is_file() and not path.is_symlink():
            continue
        if not is_agentwork_owned_retired_adapter(
            rel,
            path,
            previous,
            previous_receipt_exists,
        ):
            preserved.append(rel)
            continue
        removed.append(rel)
    return tuple(removed), tuple(preserved)


def prepare_retired_session_readme(
    target: Path,
) -> tuple[PreparedFile | None, bool, bool]:
    path = target / RETIRED_SESSION_README_REL
    if not path.exists() and not path.is_symlink():
        return None, False, False
    if path.is_symlink() or not path.is_file():
        return None, False, True
    try:
        text = path.read_bytes().decode('utf-8')
    except (OSError, UnicodeError):
        return None, False, True

    if (
        text.count(RETIRED_SESSION_README_START) != 1
        or text.count(RETIRED_SESSION_README_END) != 1
    ):
        return None, False, True
    start = text.find(RETIRED_SESSION_README_START)
    end = text.find(RETIRED_SESSION_README_END)
    if start >= end:
        return None, False, True

    remaining = text[:start] + text[end + len(RETIRED_SESSION_README_END):]
    if remaining.strip() in {'', RETIRED_SESSION_README_SCAFFOLD}:
        return None, True, False
    return PreparedFile(path, remaining.encode('utf-8')), False, False


def remove_retired_adapters(target: Path, paths: tuple[Path, ...]) -> None:
    for rel in paths:
        path = target / rel
        path.unlink()
        prune_empty_parents(path.parent, target)


def load_bootstrap_renderer():
    renderer = BOOTSTRAP / 'render_bootstrap.py'
    if not renderer.is_file():
        raise SystemExit(f'bootstrap renderer is missing: {renderer}')
    module_name = 'agentwork_bootstrap_renderer'
    spec = importlib.util.spec_from_file_location(module_name, renderer)
    if spec is None or spec.loader is None:
        raise SystemExit(f'cannot load bootstrap renderer: {renderer}')
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    previous_bytecode_setting = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        spec.loader.exec_module(module)
    except (Exception, KeyboardInterrupt, SystemExit):
        sys.modules.pop(module_name, None)
        raise
    finally:
        sys.dont_write_bytecode = previous_bytecode_setting
    return module


def load_tool_registry() -> dict:
    return json.loads(REGISTRY.read_text(encoding='utf-8'))


def is_path_covered(path: Path, declared_paths: set[Path]) -> bool:
    return any(path == declared or declared in path.parents for declared in declared_paths)


def collect_optional_shared_relpaths() -> set[Path]:
    relpaths: set[Path] = set()
    registry = load_tool_registry()
    for tool in registry.get('tools', []):
        tool_dir = TOOLS_ROOT / tool['dir']
        tool_meta = json.loads((tool_dir / 'tool.json').read_text(encoding='utf-8'))
        entries = tool_meta.get('entries', [])
        declared_sources = {
            Path(entry['from'])
            for entry in entries
            if entry.get('from', '').startswith('shared/') and entry.get('to', '').startswith('.shared/')
        }
        shared_dir = tool_dir / 'shared'
        missing = []
        if shared_dir.exists():
            missing = [
                path.relative_to(tool_dir)
                for path in sorted(shared_dir.rglob('*'))
                if path.is_file()
                and not is_python_cache_artifact(path.relative_to(tool_dir))
                and not is_path_covered(path.relative_to(tool_dir), declared_sources)
            ]
        if missing:
            details = ', '.join(str(path) for path in missing)
            raise SystemExit(f'optional tool shared files missing from tool.json entries ({tool_dir.name}): {details}')

        for entry in entries:
            target = entry.get('to', '')
            if target.startswith('.shared/'):
                relpaths.add(Path(target.removeprefix('.shared/')))
    return relpaths


def collect_core_shared_writes(target: Path):
    writes = []
    optional_shared_relpaths = collect_optional_shared_relpaths()
    for src in sorted(x for x in SHARED_ROOT.rglob('*') if x.is_file()):
        rel = src.relative_to(SHARED_ROOT)
        if is_python_cache_artifact(rel):
            continue
        # Session 已退役，但源端残留任务数据仍不可作为核心文件分发。
        if rel.parts and rel.parts[0] in {'project', 'case', 'session'}:
            continue
        if is_path_covered(rel, optional_shared_relpaths):
            continue
        writes.append((src, target / '.shared' / rel, 'file', 'core shared file'))
    return writes


